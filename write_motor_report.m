function write_motor_report(results,root)
%WRITE_MOTOR_REPORT 将MATLAB实算结果写入中文建模报告与管理建议书。
if nargin<2, root=fileparts(mfilename('fullpath')); end
if nargin<1
    data=load(fullfile(root,'results','results.mat'),'results'); results=data.results;
end
r=results; summary=r.summary;
loss=@(n) [1 n/1000 (30+0.02*n)/60 (n/1000)^2 ...
    n/1000*(30+0.02*n)/60 ((30+0.02*n)/60)^2]*r.fit.beta;
critical=fzero(@(n)25+2*r.thermal.R*loss(n)-90,[500 1500]);
energySaving=100*(1-r.fine.energy/r.baseline.energy);
costSaving=100*(1-r.fine.cost/r.baseline.cost);
displayNames=["基准方案";"名义调度100转网格";"细化调度50转网格";"名义方案在联合最坏条件回放";...
    "35℃单因素重优化";"负载增加10%重优化";"订单5500件重优化";...
    "联合最坏鲁棒8小时";"鲁棒延时30分钟";"鲁棒升级风机";"鲁棒延时并升级风机"];
lines=["## 9 实际计算结果";"";...
    "以下数值由本机MATLAB实际运行后写入，原始日志和MAT结果随文件提供。";"";...
    "### 9.1 总体指标";"";...
    "| 方案 | 电量/kWh | 电费/元 | 最高温度/℃ | 最终产量/件 | 启动次数 | 可行 | MILP间隙/% |";...
    "|---|---:|---:|---:|---:|---:|---|---:|"];
for k=1:height(summary)
    gap="—";
    if isfinite(summary.RelativeGap(k)), gap=compose("%.4f",100*summary.RelativeGap(k)); end
    pass="是"; if ~summary.Feasible(k), pass="否"; end
    lines(end+1)=compose("| %s | %.4f | %.4f | %.4f | %.1f | %d | %s | %s |",...
        displayNames(k),summary.Energy_kWh(k),summary.Cost_yuan(k),summary.MaxTemp_C(k),...
        summary.Production(k),summary.Starts(k),pass,gap); %#ok<AGROW>
end
lines=[lines;"";compose("相对基准，50 r/min细化方案节电%.3f%%、节费%.3f%%，每班节省%.4f元。它相对100 r/min方案的电费差为%.4f元，约为%.3f%%。该差异小于两个方案各自的最优间隙量级，不能全部归因为速度离散误差。",...
    energySaving,costSaving,r.baseline.cost-r.fine.cost,r.nominal.cost-r.fine.cost,...
    100*(r.nominal.cost-r.fine.cost)/r.nominal.cost);"";...
    compose("名义100 r/min方案的电费下界为%.6f元，上界为%.6f元。这个界限只针对该离散MILP，不是原连续控制问题的界限。",...
    r.nominal.cost-r.nominal.solverOutput.absolutegap,r.nominal.cost);"";...
    compose("单因素重优化显示：环境升高10 ℃的电费增量约%.4f元；负载增加10%%的电费增量约%.4f元；订单增加10%%的电费增量约%.4f元。对应负载和订单的有限差分成本弹性约为%.3f与%.3f。在本题给定扰动幅度内，订单与负载对电费的影响明显大于环境温度；这些是有限情景对比，不能解释为任意工况下的局部导数。",...
    r.scenarios{1}.cost-r.nominal.cost,r.scenarios{2}.cost-r.nominal.cost,...
    r.scenarios{3}.cost-r.nominal.cost,(r.scenarios{2}.cost/r.nominal.cost-1)/.1,...
    (r.scenarios{3}.cost/r.nominal.cost-1)/.1);"";...
    "### 9.2 代表性转速下的能效与温度";"";...
    "| 转速/(r/min) | 损耗/W | 电机效率/% | 单件电耗/Wh | 开风机平衡温度/℃ | 关风机平衡温度/℃ | 关风机首次90℃/min |";...
    "|---|---:|---:|---:|---:|---:|---:|"];
for n=[500 750 1000 1250 1500]
    L=loss(n); P=2*pi*n*(30+0.02*n)/60;
    eqOn=25+r.thermal.R*L; eqOff=25+2*r.thermal.R*L; hit="永不达到";
    if eqOff>90
        hit=compose("%.3f",-2*r.thermal.R*r.thermal.C/60*log((eqOff-90)/(eqOff-30)));
    end
    lines(end+1)=compose("| %d | %.3f | %.3f | %.4f | %.3f | %.3f | %s |",...
        n,L,100*P/(P+L),(P+L)/(600*n)*1000,eqOn,eqOff,hit); %#ok<AGROW>
end
lines=[lines;"";compose("风机关闭时的长期安全转速临界值为%.4f r/min；整数转速不高于1009 r/min时满足长期温度上限。",critical);...
    "";"### 9.3 细化名义方案的分时段统计";"";...
    "下表是控制计划的统计，不可把平均转速当作已验证的恒定转速运行表；精确执行时间表见[fine_speed_grid_schedule.csv](results/fine_speed_grid_schedule.csv)。";"";...
    "| 时段 | 平均转速/(r/min) | 时段产量/件 | 累计产量/件 | 风机开启/min |";...
    "|---|---:|---:|---:|---:|"];
for j=1:4
    idx=(j-1)*24+(1:24); s=r.fine;
    lines(end+1)=compose("| %02d:00—%02d:00 | %.3f | %.1f | %.1f | %.0f |",...
        8+2*(j-1),10+2*(j-1),mean(s.n(idx)),sum(s.n(idx))*.01*5,...
        s.production(idx(end)+1),sum(s.fan(idx))*5); %#ok<AGROW>
end
lines=[lines;"";"### 9.4 鲁棒验证与措施选择";"";...
    compose("联合最坏情景下原名义方案最高温度为%.3f ℃，且最终只有%.0f件，不能满足5500件订单。鲁棒计划在全部27个组合中通过交付和温度核验，27个场景的最高温度最大值为%.4f ℃。",...
    r.replay.maxTemp,r.replay.production(end),max(r.robustValidation(:,4)));"";...
    compose("在追加500件允许16:30交付的前提下，延时方案电费为%.4f元；原时限升级风机方案电费为%.4f元；原风机8小时鲁棒方案电费为%.4f元。三者的生产量均为5500件。",...
    r.scenarios{5}.cost,r.scenarios{6}.cost,r.scenarios{4}.cost);"";...
    "用各自求解器上下界比较，而非只比较近似目标值：";"";...
    "| 鲁棒方案 | 电费下界/元 | 已验证方案电费/元 |";...
    "|---|---:|---:|"];
for j=4:7
    s=r.scenarios{j};
    lines(end+1)=compose("| %s | %.6f | %.6f |",displayNames(j+4),...
        s.cost-s.solverOutput.absolutegap,s.cost); %#ok<AGROW>
end
extend=r.scenarios{5}; upgrade=r.scenarios{6};
if extend.cost < upgrade.cost-upgrade.solverOutput.absolutegap
    decision="延时方案的可行电费已低于升级方案的最优下界，在当前离散模型与交期口径下，延时的电费优势已得到界限支持。";
elseif upgrade.cost < extend.cost-extend.solverOutput.absolutegap
    decision="升级方案的可行电费已低于延时方案的最优下界，在当前离散模型下，升级的电费优势已得到界限支持。";
else
    decision="两项措施的电费界限有重叠，现有求解精度不足以严格判定最优电费排序，应延长求解时间后再比较。";
end
lines=[lines;"";decision;"";...
    "若所有5500件必须在16:00交付，则不能把上述延时方案的较低电费作为同交期条件下的比较结论。实际经济选择还需扣除新增人工费和风机购置维护费。";"";...
    "### 9.5 独立复核";"";...
    "独立复核采用高精度ode45逐段积分一阶微分方程，比较解析热递推；同时重新检查交付、原5000件在16:00前完成、最短启停时间和启动次数。结果记录在[independent_verification.csv](results/independent_verification.csv)。";"";...
    "名义细化方案、鲁棒方案及其改造方案的完整控制表均在results文件夹，以对应的_schedule.csv为准。"];
path=fullfile(root,'建模报告.md');
text=string(fileread(path)); marker="<!-- NUMERICAL_RESULTS -->";
parts=split(text,marker);
writeText(path,parts(1)+marker+newline+newline+join(lines,newline));

memo=["# 工厂管理建议书";"";...
    "致生产与设备管理部门：";"";...
    compose("根据题设模拟数据，建议按订单交期与电价安排电机转速，并根据绕组温度控制风机。正常环境下，50 r/min细化方案每班生产5000件，电费约%.2f元，比现行方案%.2f元减少%.2f元（%.2f%%）；耗电量由%.2f降至%.2f kWh。",...
    r.fine.cost,r.baseline.cost,r.baseline.cost-r.fine.cost,costSaving,r.baseline.energy,r.fine.energy);"";...
    "生产安排宜在08:00—10:00和12:00—14:00较低电价时段提高产量，在高价时段降低转速。精确转速和风机开关时间按随附运行表执行，不宜仅按时段平均转速替代。";"";...
    compose("正常经济方案最高温度约%.2f ℃，接近90 ℃上限。原计划在高温重载下可能达到%.2f ℃，因此环境、负载或订单变化后必须重新排程，不宜照搬。",r.fine.maxTemp,r.replay.maxTemp);"";...
    compose("对于35 ℃、负载增加10%%、损耗增加3%%和5500件订单的联合最坏条件，8小时鲁棒方案电费约%.2f元，全部27组扰动验证均满足温度与交付要求。上述保证依赖本题热参数和生产率假设；现场应用前还需实测校准并预留温度裕量。",r.scenarios{4}.cost);"";...
    compose("若新增500件允许延至16:30交付，延时方案电费约%.2f元；坚持16:00完成而升级风机的方案约%.2f元。%s",extend.cost,upgrade.cost,decision);"";...
    "建议每5分钟记录温度、产量与负载，每30分钟或在订单变化时更新剩余计划。将电费收益与人工加班费、风机购置费、开关寿命成本一起评估后再实施设备投资。";"";...
    "本建议以教学模拟数据为依据，未接入现场设备。"];
writeText(fullfile(root,'工厂管理建议书.md'),join(memo,newline));
fprintf('Report written. Fan-off critical speed %.6f r/min.\n',critical);
end

function writeText(path,content)
fid=fopen(path,'w','n','UTF-8');
assert(fid>=0,'无法写入报告文件');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',content);
end
